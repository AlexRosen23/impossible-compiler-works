// TLA+ exporter. Produces a module whose behaviours are exactly the model's behaviours under
// TLA+ semantics (see docs/TLC_COMPATIBILITY.md). Each instantiated action becomes its own
// operator, so TLC trace labels map 1:1 back to WML action labels.
import type { CompiledModel, IrExpr } from '../model/ir.ts';

export interface TlaExport {
  moduleName: string;
  tla: string;
  cfgAll: string;
  varNames: string[]; // TLA name per model variable index
  opToLabel: Record<string, string>; // TLA operator name -> WML action label
  configs: { name: string; purpose: string; cfg: string }[];
}

const RESERVED = new Set([
  'ASSUME', 'ASSUMPTION', 'AXIOM', 'BOOLEAN', 'CASE', 'CHOOSE', 'CONSTANT', 'CONSTANTS', 'DOMAIN', 'ELSE', 'ENABLED',
  'EXCEPT', 'EXTENDS', 'FALSE', 'IF', 'IN', 'INSTANCE', 'LET', 'LOCAL', 'MODULE', 'OTHER', 'SF_', 'SUBSET', 'THEN',
  'THEOREM', 'TRUE', 'UNCHANGED', 'UNION', 'VARIABLE', 'VARIABLES', 'WF_', 'WITH', 'Init', 'Next', 'Spec', 'vars',
  'TypeOK', 'Terminating', 'Fairness', 'Nat', 'Int', 'Integers', 'Naturals',
]);

function sanitize(raw: string, used: Set<string>): string {
  let base = raw.replace(/[^A-Za-z0-9_]/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '') || 'x';
  if (/^[0-9]/.test(base)) base = `v_${base}`;
  if (RESERVED.has(base)) base = `${base}_`;
  let name = base;
  let k = 2;
  while (used.has(name)) name = `${base}_${k++}`;
  used.add(name);
  return name;
}

export function tlaString(s: string): string {
  // WML literals are identifiers, so they never contain quotes or backslashes.
  return `"${s}"`;
}

export function exportTla(m: CompiledModel): TlaExport {
  const used = new Set<string>();
  const moduleName = sanitize(`Witness_${m.name}`, used);
  const varNames = m.vars.map((v) => sanitize(v.name.replace('.', '_'), used));
  const propNames = new Map<string, string>();
  for (const p of [...m.invariants, ...m.liveness]) propNames.set(p.name, sanitize(p.name, used));
  const opNames = m.actions.map((a) => sanitize(a.label.replace('.', '_').replace(/[(),=]/g, '_'), used));
  const opToLabel: Record<string, string> = {};
  opNames.forEach((o, i) => (opToLabel[o] = m.actions[i].label));

  const val = (t: 'int' | 'bool' | 'enum', v: number) => (t === 'int' ? (v < 0 ? `(${v})` : String(v)) : t === 'bool' ? (v ? 'TRUE' : 'FALSE') : tlaString(m.literals[v]));
  const ex = (e: IrExpr): string => {
    switch (e.k) {
      case 'const': return val(e.t, e.v);
      case 'var': return varNames[e.i];
      case 'un': return e.op === 'not' ? `~(${ex(e.a)})` : `-(${ex(e.a)})`;
      case 'ite': return `(IF ${ex(e.c)} THEN ${ex(e.t)} ELSE ${ex(e.e)})`;
      case 'bin': {
        const op = { and: '/\\', or: '\\/', implies: '=>', '=': '=', '!=': '#', '<': '<', '<=': '<=', '>': '>', '>=': '>=', '+': '+', '-': '-', '*': '*', '%': '%' }[e.op];
        return `(${ex(e.a)} ${op} ${ex(e.b)})`;
      }
    }
  };
  const domainSet = (i: number, values?: number[]): string => {
    const v = m.vars[i];
    const vals = values ?? v.domain;
    if (v.type.kind === 'bool') return vals.length === 2 ? 'BOOLEAN' : `{${vals.map((x) => (x ? 'TRUE' : 'FALSE')).join(', ')}}`;
    if (v.type.kind === 'enum') return `{${vals.map((x) => tlaString(m.literals[x])).join(', ')}}`;
    const sorted = [...vals].sort((a, b) => a - b);
    const contiguous = sorted.every((x, k) => k === 0 || x === sorted[k - 1] + 1);
    return contiguous ? `${val('int', sorted[0])}..${val('int', sorted[sorted.length - 1])}` : `{${sorted.map((x) => val('int', x)).join(', ')}}`;
  };

  const L: string[] = [];
  L.push(`---- MODULE ${moduleName} ----`);
  L.push(`\\* Generated by THE IMPOSSIBLE WITNESS from WML model '${m.name}'.`);
  L.push(`\\* Semantics: interleaving of atomic actions; each action is a conjunction of a guard,`);
  L.push(`\\* primed assignments and UNCHANGED for every variable it does not assign.`);
  L.push('EXTENDS Integers');
  L.push('');
  L.push(`VARIABLES ${varNames.join(', ')}`);
  L.push(`vars == <<${varNames.join(', ')}>>`);
  L.push('');
  L.push('TypeOK ==');
  m.vars.forEach((v, i) => L.push(`    /\\ ${varNames[i]} \\in ${domainSet(i)}`));
  L.push('');
  L.push('Init ==');
  m.vars.forEach((v, i) => L.push(v.init.length === 1 ? `    /\\ ${varNames[i]} = ${val(v.type.kind, v.init[0])}` : `    /\\ ${varNames[i]} \\in ${domainSet(i, v.init)}`));
  L.push('');
  m.actions.forEach((a, k) => {
    L.push(`\\* ${a.label}`);
    L.push(`${opNames[k]} ==`);
    if (a.guard) L.push(`    /\\ ${ex(a.guard)}`);
    for (const as of a.assigns) L.push(`    /\\ ${varNames[as.v]}' = ${ex(as.e)}`);
    const assigned = new Set(a.assigns.map((x) => x.v));
    const unchanged = m.vars.filter((v) => !assigned.has(v.index)).map((v) => varNames[v.index]);
    if (unchanged.length) L.push(`    /\\ UNCHANGED <<${unchanged.join(', ')}>>`);
    if (!a.guard && !a.assigns.length && !unchanged.length) L.push('    /\\ TRUE');
    L.push('');
  });
  const nextParts = [...opNames];
  if (m.terminal) {
    L.push('\\* Intended termination: lets TLC distinguish a finished run from a deadlock.');
    L.push(`Terminating == ${ex(m.terminal)} /\\ UNCHANGED vars`);
    L.push('');
    nextParts.push('Terminating');
  }
  L.push(`Next == ${nextParts.length ? nextParts.join(' \\/ ') : 'FALSE'}`);
  L.push('');
  const fair = m.fairness.map((f) => `${f.strength === 'weak' ? 'WF' : 'SF'}_vars(${f.actions.map((i) => opNames[i]).join(' \\/ ') || 'FALSE'})`);
  L.push(`Fairness == ${fair.length ? fair.join(' /\\ ') : 'TRUE'}`);
  L.push('Spec == Init /\\ [][Next]_vars /\\ Fairness');
  L.push('');
  for (const inv of m.invariants) L.push(`${propNames.get(inv.name)} == ${ex(inv.expr)}`);
  for (const l of m.liveness) {
    L.push(l.kind === 'eventually' ? `${propNames.get(l.name)} == <>(${ex(l.q)})` : `${propNames.get(l.name)} == (${ex(l.p!)}) ~> (${ex(l.q)})`);
  }
  L.push('====');
  const tla = L.join('\n') + '\n';

  const cfg = (lines: string[]) => ['SPECIFICATION Spec', ...lines].join('\n') + '\n';
  const configs: TlaExport['configs'] = [];
  configs.push({ name: 'full', purpose: 'complete reachable state count + TypeOK', cfg: cfg(['INVARIANT TypeOK', 'CHECK_DEADLOCK FALSE']) });
  configs.push({ name: 'deadlock', purpose: 'DeadlockFreedom', cfg: cfg(['CHECK_DEADLOCK TRUE']) });
  for (const inv of m.invariants) configs.push({ name: `inv:${inv.name}`, purpose: inv.name, cfg: cfg([`INVARIANT ${propNames.get(inv.name)}`, 'CHECK_DEADLOCK FALSE']) });
  for (const l of m.liveness) configs.push({ name: `live:${l.name}`, purpose: l.name, cfg: cfg([`PROPERTY ${propNames.get(l.name)}`, 'CHECK_DEADLOCK FALSE']) });
  const cfgAll = cfg([
    'INVARIANT TypeOK',
    ...m.invariants.map((i) => `INVARIANT ${propNames.get(i.name)}`),
    ...m.liveness.map((l) => `PROPERTY ${propNames.get(l.name)}`),
  ]);
  return { moduleName, tla, cfgAll, varNames, opToLabel, configs };
}
