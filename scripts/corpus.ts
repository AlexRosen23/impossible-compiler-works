// Corpus runner.
//   node scripts/corpus.ts --write-expected   regenerate tests/fixtures/expected.json (review the diff!)
//   node scripts/corpus.ts --tlc               cross-check every example with TLC -> evidence/tlc-crosscheck.{json,md}
//   node scripts/corpus.ts --bench             benchmark -> evidence/benchmarks.{json,md}
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileSource } from '../src/core/model/compile.ts';
import { check } from '../src/core/engine/check.ts';
import { runTlcCrossCheck } from '../src/core/tla/tlc.ts';
import { gitInfo } from '../src/core/receipt/receipt.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const exDir = path.join(root, 'examples');
const files = readdirSync(exDir).filter((f) => f.endsWith('.witness')).sort();
const HAND = new Set(['counter-race', 'counter-atomic', 'mutex-test-and-set', 'bounded-counter', 'bounded-counter-unfair', 'state-explosion', 'benchmark-grid']);

if (process.argv.includes('--write-expected')) {
  const out: Record<string, unknown> = {};
  for (const f of files) {
    const slug = f.replace(/\.witness$/, '');
    const c = compileSource(readFileSync(path.join(exDir, f), 'utf8'));
    if (!c.ok) throw new Error(`${f}: ${c.diagnostics[0].message}`);
    const { result } = check(c.model!, { includeGraph: false });
    out[slug] = {
      verdict: result.verdict, states: result.stats.states, edges: result.stats.edges, maxDepth: result.stats.maxDepth,
      properties: Object.fromEntries(result.properties.map((p) => [p.name, p.trace ? { status: p.status, witnessLength: p.trace.length } : { status: p.status }])),
      oracle: HAND.has(slug) ? 'hand-derived counts (see docs/SEARCH_ALGORITHMS.md) + TLC' : 'regression snapshot, cross-checked with TLC (evidence/tlc-crosscheck.md)',
    };
  }
  writeFileSync(path.join(root, 'tests/fixtures/expected.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote expectations for ${files.length} models`);
}

if (process.argv.includes('--tlc')) {
  const rows: unknown[] = [];
  const md: string[] = ['# TLC cross-check corpus', '', `Generated by \`node scripts/corpus.ts --tlc\` at ${new Date().toISOString()} on ${os.cpus()[0]?.model ?? os.arch()} (${os.platform()}-${os.arch()}), git ${gitInfo().commit.slice(0, 10)}.`, '',
    'Each model is exported to TLA+ and checked by TLC once per property (invariants one at a time, deadlock, TypeOK + full state count, each liveness property). Every TLC counterexample is converted back to model variables and re-derived by the independent replay evaluator.', '',
    '| model | comparison | internal | TLC | agree | note |', '|---|---|---|---|---|---|'];
  let agree = 0, total = 0;
  for (const f of files) {
    if (f === 'benchmark-grid.witness') continue;
    const src = readFileSync(path.join(exDir, f), 'utf8');
    const c = compileSource(src);
    const { result } = check(c.model!, { includeGraph: false });
    const t = await runTlcCrossCheck(src, c.model!, result);
    rows.push({ model: f, tlc: t });
    for (const k of t.comparison ?? []) {
      total++; if (k.agree) agree++;
      md.push(`| ${f.replace('.witness', '')} | ${k.property} | ${k.internal} | ${k.tlc} | ${k.agree ? 'yes' : '**NO**'} | ${k.note.replace(/\|/g, '/')} |`);
    }
    if (!t.available) md.push(`| ${f} | — | — | — | — | ${t.note} |`);
    process.stdout.write(`${f}: ${t.note}\n`);
  }
  md.splice(4, 0, `**Result: ${agree}/${total} comparisons agree.**`, '');
  mkdirSync(path.join(root, 'evidence'), { recursive: true });
  writeFileSync(path.join(root, 'evidence/tlc-crosscheck.json'), JSON.stringify(rows, null, 2) + '\n');
  writeFileSync(path.join(root, 'evidence/tlc-crosscheck.md'), md.join('\n') + '\n');
  console.log(`${agree}/${total} comparisons agree`);
}

if (process.argv.includes('--bench')) {
  const cases = ['counter-race', 'polite-livelock', 'two-phase-presumed-commit', 'state-explosion', 'benchmark-grid'];
  const md = ['# Benchmarks', '', `Machine: ${os.cpus()[0]?.model} × ${os.cpus().length}, ${Math.round(os.totalmem() / 2 ** 30)} GiB, ${os.platform()}-${os.arch()}, Node ${process.version}. Git ${gitInfo().commit.slice(0, 10)}${gitInfo().dirty ? ' (dirty)' : ''}. Command: \`node scripts/corpus.ts --bench\`. Median of 5 runs, graph payload disabled.`, '',
    '| model | states | edges | depth | median ms | states/s | peak heap MB |', '|---|---|---|---|---|---|---|'];
  const out: unknown[] = [];
  for (const slug of cases) {
    const c = compileSource(readFileSync(path.join(exDir, `${slug}.witness`), 'utf8'));
    const times: number[] = [];
    let last;
    for (let i = 0; i < 5; i++) {
      const t0 = performance.now();
      last = check(c.model!, { includeGraph: false, bounds: { maxStates: 2_000_000, maxEdges: 20_000_000, timeLimitMs: 120_000 } }).result;
      times.push(performance.now() - t0);
    }
    times.sort((a, b) => a - b);
    const med = times[2];
    out.push({ slug, states: last!.stats.states, edges: last!.stats.edges, medianMs: med, heapMB: last!.stats.peakHeapMB });
    md.push(`| ${slug} | ${last!.stats.states} | ${last!.stats.edges} | ${last!.stats.maxDepth} | ${med.toFixed(1)} | ${Math.round(last!.stats.states / (med / 1000)).toLocaleString('en-US')} | ${last!.stats.peakHeapMB} |`);
  }
  writeFileSync(path.join(root, 'evidence/benchmarks.json'), JSON.stringify(out, null, 2) + '\n');
  writeFileSync(path.join(root, 'evidence/benchmarks.md'), md.join('\n') + '\n');
  console.log(md.join('\n'));
}
